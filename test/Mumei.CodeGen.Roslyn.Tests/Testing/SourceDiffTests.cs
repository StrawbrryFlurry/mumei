using Mumei.CodeGen.Roslyn.Testing.Diffing;
using Xunit.Sdk;

namespace Mumei.CodeGen.Roslyn.Testing.Tests;

public sealed class SourceDiffTests {
    private static readonly SourceComparisonOptions NoColors = new() { UseColors = false };

    [Fact]
    public void Compare_IgnoresIndentationLineEndingsAndOuterBlankLinesByDefault() {
        var result = SourceDiff.Compare(
            "class A {\n    int  x;\n}",
            "\r\n  class A {\r\n\tint x;\r\n}\r\n\r\n"
        );

        Assert.True(result.IsMatch);
    }

    [Fact]
    public void Compare_ExactWhitespace_ReportsIndentationDifference() {
        var result = SourceDiff.Compare("class A {\n    int x;\n}", "class A {\n  int x;\n}", new() { Whitespace = WhitespaceHandling.Exact });

        var changed = Assert.Single(result.Lines, x => x.IsDifference);
        Assert.Equal(SourceDiffLineKind.Changed, changed.Kind);
        Assert.Equal([new SourceTextRange(0, 4)], changed.ExpectedChanges);
        Assert.Equal([new SourceTextRange(0, 2)], changed.ActualChanges);
    }

    [Fact]
    public void Compare_ChangedLine_ReportsLineNumbersAndChangedTokens() {
        var result = SourceDiff.Compare(
            """
            class A {
                public int Value { get; }
            }
            """,
            """
            // <auto-generated/>
            class A {
                public long Value { get; }
            }
            """
        );

        Assert.False(result.IsMatch);
        Assert.Equal(1, result.UnexpectedLineCount);
        var changed = Assert.Single(result.Lines, x => x.Kind == SourceDiffLineKind.Changed);
        Assert.Equal(2, changed.ExpectedLineNumber);
        Assert.Equal(3, changed.ActualLineNumber);
        Assert.Equal("int", Slice(changed.ExpectedText!, Assert.Single(changed.ExpectedChanges)));
        Assert.Equal("long", Slice(changed.ActualText!, Assert.Single(changed.ActualChanges)));
    }

    [Fact]
    public void Compare_DissimilarLines_AreReportedAsMissingAndUnexpected() {
        var result = SourceDiff.Compare("a();\nfirst();\nsecond();\nb();", "a();\nsomethingElse(42);\nb();");

        Assert.Equal(0, result.ChangedLineCount);
        Assert.Equal(
            [(SourceDiffLineKind.Missing, 2, null), (SourceDiffLineKind.Missing, 3, null), (SourceDiffLineKind.Unexpected, null, 2)],
            result.Lines.Where(x => x.IsDifference).Select(x => (x.Kind, x.ExpectedLineNumber, x.ActualLineNumber))
        );
    }

    [Fact]
    public void CompareFragment_MatchesContiguousLinesWithPartialFirstAndLastLine() {
        const string actual = """
                              namespace N {
                                  public sealed class A {
                                      public void M() { }
                                  }
                              }
                              """;

        Assert.True(SourceDiff.CompareFragment("sealed class A {\n    public void M() { }\n}", actual).IsMatch);
        Assert.True(SourceDiff.CompareFragment("void M()", actual).IsMatch);
        Assert.False(SourceDiff.CompareFragment("public sealed class A {\n}", actual).IsMatch);
    }

    [Fact]
    public void Placeholders_MatchAnyTextWithinALineAndAnyNumberOfLines() {
        const string actual = """
                              [InterceptsLocation(1, "aGVsbG8=")]
                              static void M() {
                                  var a = 1;
                                  var b = 2;
                              }
                              """;

        Assert.True(SourceDiff.Compare("[InterceptsLocation(1, \"/*...*/\")]\nstatic void M() {\n    // ...\n}", actual).IsMatch);
        Assert.True(SourceDiff.CompareFragment("static void M() {\n// ...\n    var b = 2;\n}", actual).IsMatch);
        Assert.True(SourceDiff.CompareFragment("var a = 1;\n// ...\nvar b = 2;", actual).IsMatch);
    }

    [Fact]
    public void CSharpWildcardCharacters_AreMatchedLiterally() {
        Assert.False(SourceDiff.Compare("int* p = a * b;", "int p = a + b;").IsMatch);
        Assert.False(SourceDiff.Compare("string? s;", "string! s;").IsMatch);
    }

    [Fact]
    public void CompareFragment_NotFound_AlignsWithTheMostSimilarRegion() {
        const string actual = """
                              class Unrelated {
                                  void X() { }
                              }

                              class A {
                                  void M() {
                                      Call(1);
                                  }
                              }
                              """;

        var result = SourceDiff.CompareFragment("void M() {\n    Call(2);\n}", actual);

        Assert.False(result.IsMatch);
        var changed = Assert.Single(result.Lines, x => x.IsDifference);
        Assert.Equal(SourceDiffLineKind.Changed, changed.Kind);
        Assert.Equal(7, changed.ActualLineNumber);
        Assert.Equal("2", Slice(changed.ExpectedText!, Assert.Single(changed.ExpectedChanges)));
        Assert.Equal("1", Slice(changed.ActualText!, Assert.Single(changed.ActualChanges)));
        Assert.Equal(SourceDiffLineKind.Outside, result.Lines[0].Kind);
    }

    [Fact]
    public void CompareFragment_ChangedFirstLine_IsReportedAsChangedInsteadOfMissing() {
        var result = SourceDiff.CompareFragment(
            "public int M() {\n    return 1;\n}",
            "class A {\n    public long M() {\n        return 1;\n    }\n}"
        );

        var changed = Assert.Single(result.Lines, x => x.IsDifference);
        Assert.Equal((SourceDiffLineKind.Changed, 1, 2), (changed.Kind, changed.ExpectedLineNumber, changed.ActualLineNumber));
    }

    [Fact]
    public void CompareFragment_WithoutAnyMatchingLine_ReportsTheMostSimilarLineAsChanged() {
        var result = SourceDiff.CompareFragment("public int Value { get; }", "class A {\n    public long Value { get; }\n}");

        var changed = Assert.Single(result.Lines, x => x.IsDifference);
        Assert.Equal(SourceDiffLineKind.Changed, changed.Kind);
        Assert.Equal(2, changed.ActualLineNumber);
        Assert.Equal("long", Slice(changed.ActualText!, Assert.Single(changed.ActualChanges)));
    }

    [Fact]
    public void Format_DescribesTheFirstDifferenceAndMarksChangedText() {
        var message = SourceDiff.Compare("class A {\n    int x;\n}", "class A {\n    long x;\n}", NoColors).Format("A.g.cs");

        Assert.DoesNotContain("\e[", message);
        Assert.Contains("Source        A.g.cs", message);
        Assert.Contains("First difference at expected line 2:5, actual line 2:5:", message);
        Assert.Contains("expected: `int`", message);
        Assert.Contains("actual:   `long`", message);
        Assert.Contains(
            """
            - 2   │     int x;
                  │     ^^^
            +   2 │     long x;
                  │     ^^^^
            """.ReplaceLineEndings(),
            message
        );
    }

    [Fact]
    public void SourceAssert_ThrowsWithDiffOnlyOnMismatch() {
        SourceAssert.Equal("class A { }", "class  A { }\n");

        var exception = Assert.Throws<XunitException>(() => SourceAssert.Contains("class B", "class A { }", NoColors));
        Assert.Contains("The expected fragment was not found in the source.", exception.Message);
        Assert.Contains("Hint: None of the expected lines occur in the source", exception.Message);
    }

    private static string Slice(string text, SourceTextRange range) {
        return text.Substring(range.Start, range.Length);
    }
}
