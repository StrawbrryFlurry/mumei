namespace Mumei.CodeGen.Tests.Output;

public sealed class SourceFileBuilderTests {
    [Fact]
    public void Class_WithMembers_RendersMembersAndReferencesThemByName() {
        var file = new SourceFileBuilder();
        var counter = file.Namespace("MyApp").Class("Counter", Modifiers.Public | Modifiers.Sealed);
        var count = counter.Field<int>("_count");
        var label = counter.Field<string>("_label", Modifiers.Private | Modifiers.Readonly, Code.Literal("counter"));
        counter.Property<int>("Count").Get($"{count}");
        var increment = counter.Method("Increment");
        var by = increment.Parameter<int>("by");
        increment.Body($"{count} += {by};");
        counter.Method<string>("Describe").Body(body => {
            body.Block($"if ({count} == 0)", then => then.Line($"return {label};"));
            body.Line($"return {label} + {count};");
        });

        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace MyApp;

            public sealed class Counter {
                private int _count;
                private readonly string _label = "counter";

                public int Count => _count;

                public void Increment(int by) {
                    _count += by;
                }

                public string Describe() {
                    if (_count == 0) {
                        return _label;
                    }
                    return _label + _count;
                }
            }

            """.ReplaceLineEndings("\n"),
            file.ToString()
        );
    }

    [Fact]
    public void Code_Holes_FormatTypesLiteralsAndVerbatimStrings() {
        var identifier = "value";
        Code code = $"{typeof(List<int>)} {identifier} = new(); {"a\"b":literal}; {TypeRef.Of<string>():typeof}; {true}; {DayOfWeek.Friday}";

        Assert.Equal(
            "global::System.Collections.Generic.List<int> value = new(); \"a\\\"b\"; typeof(string); true; global::System.DayOfWeek.Friday",
            code.ToString()
        );
    }

    [Fact]
    public void Extend_NestedGenericType_DeclaresPartialContainingTypesOnce() {
        var outer = TypeRef.Named("global::MyApp.Outer<T>") with { Name = "Outer", Namespace = "MyApp", IsClass = true, TypeArguments = [TypeRef.TypeParameter("T")] };
        var inner = new TypeModel {
            Type = TypeRef.Named("global::MyApp.Outer<T>.Inner") with { Name = "Inner", Namespace = "MyApp", IsStruct = true, IsRecord = true },
            ContainingTypes = [outer]
        };

        var file = new SourceFileBuilder();
        file.Extend(inner).Method<string>("Describe", Modifiers.Public | Modifiers.Override).ExpressionBody($"\"inner\"");
        file.Extend(inner).Field<int>("_extra");

        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace MyApp;

            partial class Outer<T> {
                partial record struct Inner {
                    public override string Describe() => "inner";

                    private int _extra;
                }
            }

            """.ReplaceLineEndings("\n"),
            file.ToString()
        );
    }
}
