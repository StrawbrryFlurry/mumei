using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Mumei.Roslyn.Testing;
using static Mumei.Roslyn.Testing.SourceGeneratorTest;

namespace Mumei.CodeGen.Tests.Pipeline;

public sealed class PipelineTests {
    private const string ReprSource =
        """
        namespace App;

        [System.AttributeUsage(System.AttributeTargets.Class)]
        public sealed class ReprAttribute : System.Attribute;

        [Repr]
        public sealed partial class User {
            public string Name { get; set; } = "";
            public int Age { get; set; }
        }
        """;

    private static void GenerateRepr(GeneratorContext gen) {
        gen.TypesWith("App.ReprAttribute").Generate((type, output) => {
            var members = Code.Join(", ", type.Properties, p => $"{p.Name} = {{{p}}}");
            output.Extend(type)
                .Method<string>("ToString", Modifiers.Public | Modifiers.Override)
                .ExpressionBody($"$\"{type.Name} {{{{ {members} }}}}\"");
        });
    }

    [Fact]
    public void TypesWith_Extend_GeneratesPartialMembers() {
        MumeiGeneratorTest(b => b.AddSource("User.cs", ReprSource), GenerateRepr)
            .RunWithAssert(result => result.HasFileMatching("*User.*.g.cs").WithContent(
                $$$"""
                // <auto-generated/>
                #nullable enable

                namespace App;

                partial class User {
                    public override string ToString() => $"User {{ Name = {Name}, Age = {Age} }}";
                }

                """
            ));
    }

    [Fact]
    public void TypesWith_UnrelatedEdit_CachesOutput() {
        MumeiGeneratorTest(b => b.AddSource("User.cs", ReprSource).AddSource("Other.cs", "namespace App; class Other;"), GenerateRepr)
            .RunWithAssert(_ => { })
            .UpdateCompilation(c => c.UpdateFile("Other.cs", "namespace App; class Other { void M() { } }"))
            .RunWithAssert(result => {
                Assert.NotEmpty(result.OutputReasons);
                Assert.All(result.OutputReasons, reason => Assert.Equal(IncrementalStepRunReason.Cached, reason));
            })
            .UpdateCompilation(c => c.UpdateFile("User.cs", text => text.Replace("public int Age", "public long Age")))
            .RunWithAssert(result => Assert.Contains(IncrementalStepRunReason.Modified, result.OutputReasons));
    }

    [Fact]
    public void CallsTo_Intercept_GeneratesInterceptorsForInstanceStaticAndExtensionCalls() {
        const string source =
            """
            namespace App;

            public sealed class Greeter {
                public string Greet(string name) => "Hello " + name;
                public static T Echo<T>(T value) => value;
            }

            public static class GreeterExtensions {
                public static string Shout(this Greeter greeter, string name) => greeter.Greet(name).ToUpper();
            }

            public static class Program {
                public static string Run() {
                    var greeter = new Greeter();
                    return greeter.Greet("a") + Greeter.Echo(1) + greeter.Shout("b");
                }
            }
            """;

        MumeiGeneratorTest(b => b.AddSource("Greeter.cs", source), gen => {
            gen.CallsTo("App.Greeter", "Greet").Intercept(i => i.ExpressionBody($"\"[\" + {i.Proceed()} + \"]\""));
            gen.CallsTo("App.Greeter", "Echo").Intercept(i => i.Body(i.ReturnProceed()));
            gen.CallsTo("App.GreeterExtensions", "Shout").Intercept(i => i.Body(i.ReturnProceed()));
        }).RunWithAssert(result => {
            result.HasFileMatching("*GreetInterceptor.*.g.cs").WithPartialContent(
                $$"""
                namespace Mumei.Generated {
                    file static class GreetInterceptor {
                        [global::System.Runtime.CompilerServices.InterceptsLocation(1, "*")]
                        public static string Intercept(this global::App.Greeter @this, string name) => "[" + @this.Greet(name) + "]";
                    }
                }
                """
            );
            result.HasFileMatching("*EchoInterceptor.*.g.cs").WithPartialContent(
                $$"""
                        public static int Intercept(int value) {
                            return global::App.Greeter.Echo<int>(value);
                        }
                """
            );
            result.HasFileMatching("*ShoutInterceptor.*.g.cs").WithPartialContent(
                $$"""
                        public static string Intercept(this global::App.Greeter greeter, string name) {
                            return global::App.GreeterExtensions.Shout(greeter, name);
                        }
                """
            );
        });
    }

    [Fact]
    public void Generate_ThrowingGenerator_ReportsDiagnosticInsteadOfCrashing() {
        var compilation = CSharpCompilation.Create(
            "Test",
            [CSharpSyntaxTree.ParseText(ReprSource)],
            [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]
        );
        var generator = new MumeiTestGenerator(gen => gen.TypesWith("App.ReprAttribute")
            .Generate((_, _) => throw new InvalidOperationException("boom")));

        var result = CSharpGeneratorDriver.Create(generator).RunGenerators(compilation).GetRunResult();

        var diagnostic = Assert.Single(result.Diagnostics);
        Assert.Equal("MUMEI001", diagnostic.Id);
        Assert.Contains("boom", diagnostic.GetMessage());
        Assert.Null(result.Results[0].Exception);
    }

    [Fact]
    public void Cacheability_RejectsSymbolsAndReferenceComparedCollections() {
        var symbol = Assert.Throws<InvalidOperationException>(() => Cacheability.Ensure(typeof((TypeRef Type, ITypeSymbol Symbol)), "Select"));
        Assert.Contains("'ValueTuple<TypeRef, ITypeSymbol>.Item2' is a ISymbol", symbol.Message);
        Assert.Contains("ToTypeRef()", symbol.Message);

        var array = Assert.Throws<InvalidOperationException>(() => Cacheability.Ensure(typeof(HandlerWithArray), "Select"));
        Assert.Contains("'HandlerWithArray.Requests' is an array", array.Message);

        Cacheability.Ensure(typeof(Handler), "Select");
        Cacheability.Ensure(typeof((CallSite Call, string Expression)), "Select");
    }

    private sealed record Handler(TypeModel Type, EquatableArray<TypeRef> Requests, int? Order);

    private sealed record HandlerWithArray(TypeModel Type, TypeRef[] Requests);
}
