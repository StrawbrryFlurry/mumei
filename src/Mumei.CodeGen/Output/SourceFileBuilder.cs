using Mumei.CodeGen.Rendering;

namespace Mumei.CodeGen;

/// <summary>Declares types within a namespace. Declaring a type with the same name and kind twice returns the existing builder.</summary>
public sealed class NamespaceBuilder {
    private readonly List<MemberBuilder> _members = [];

    internal NamespaceBuilder(string name) {
        Name = name;
    }

    /// <summary>The namespace name, or an empty string for the global namespace.</summary>
    public string Name { get; }

    internal IReadOnlyList<MemberBuilder> Members => _members;

    public TypeBuilder Class(string name, Modifiers modifiers = Modifiers.Public) {
        return Type(name, TypeDeclarationKind.Class, modifiers);
    }

    public TypeBuilder Struct(string name, Modifiers modifiers = Modifiers.Public) {
        return Type(name, TypeDeclarationKind.Struct, modifiers);
    }

    public TypeBuilder Interface(string name, Modifiers modifiers = Modifiers.Public) {
        return Type(name, TypeDeclarationKind.Interface, modifiers);
    }

    public TypeBuilder Record(string name, Modifiers modifiers = Modifiers.Public) {
        return Type(name, TypeDeclarationKind.Record, modifiers);
    }

    public TypeBuilder RecordStruct(string name, Modifiers modifiers = Modifiers.Public) {
        return Type(name, TypeDeclarationKind.RecordStruct, modifiers);
    }

    /// <summary>Declares the class described by <paramref name="template"/> in this namespace.</summary>
    public TypeBuilder Add(ClassTemplate template) {
        return template.Render(this);
    }

    /// <summary>Adds a type or other top-level declaration from verbatim code.</summary>
    public NamespaceBuilder Member(Code declaration) {
        _members.Add(new RawMemberBuilder(declaration));
        return this;
    }

    internal TypeBuilder Type(string name, TypeDeclarationKind kind, Modifiers modifiers) {
        foreach (var member in _members) {
            if (member is TypeBuilder existing && existing.Name == name && existing.Kind == kind) {
                existing.Modifiers |= modifiers;
                return existing;
            }
        }

        var type = new TypeBuilder(name, kind, modifiers, Name, null);
        _members.Add(type);
        return type;
    }
}

/// <summary>A generated source file made up of namespaces and their types.</summary>
public sealed class SourceFileBuilder {
    private readonly List<NamespaceBuilder> _namespaces = [];

    public NamespaceBuilder Global => Namespace("");

    /// <summary>Returns the namespace with the given name, declaring it on first use.</summary>
    public NamespaceBuilder Namespace(string name) {
        foreach (var existing in _namespaces) {
            if (existing.Name == name) {
                return existing;
            }
        }

        var ns = new NamespaceBuilder(name);
        _namespaces.Add(ns);
        return ns;
    }

    public bool IsEmpty => _namespaces.All(x => x.Members.Count == 0);

    /// <summary>
    /// Declares a <c>partial</c> part of an existing (user) type, including its namespace,
    /// containing types and type parameters, so that members can be added to it.
    /// </summary>
    public TypeBuilder Extend(TypeModel type) {
        var ns = Namespace(type.Namespace);
        TypeBuilder? container = null;
        foreach (var containingType in type.ContainingTypes) {
            container = Declare(containingType);
        }

        return Declare(type.Type);

        TypeBuilder Declare(TypeRef part) {
            var kind = part switch {
                { IsRecord: true, IsStruct: true } => TypeDeclarationKind.RecordStruct,
                { IsRecord: true } => TypeDeclarationKind.Record,
                { IsStruct: true } => TypeDeclarationKind.Struct,
                { IsInterface: true } => TypeDeclarationKind.Interface,
                _ => TypeDeclarationKind.Class
            };

            var builder = container is null
                ? ns.Type(part.Name, kind, Modifiers.Partial)
                : container.NestedType(part.Name, kind, Modifiers.Partial);
            if (!builder.HasTypeParameters) {
                foreach (var typeArgument in part.TypeArguments) {
                    builder.TypeParameter(typeArgument.Name);
                }
            }

            return builder;
        }
    }

    /// <summary>The name of the first declared type, used to derive a readable file name.</summary>
    internal string? FirstTypeName {
        get {
            foreach (var ns in _namespaces) {
                foreach (var member in ns.Members) {
                    if (member is TypeBuilder type) {
                        return type.Name;
                    }
                }
            }

            return null;
        }
    }

    public override string ToString() {
        using var tree = new SourceFileRenderTreeBuilder();
        tree.Line("// <auto-generated/>");
        tree.Line("#nullable enable");

        var namespaces = _namespaces.Where(x => x.Members.Count > 0).ToList();
        var useFileScopedNamespace = namespaces is [{ Name.Length: > 0 }];

        foreach (var ns in namespaces) {
            tree.NewLine();
            if (ns.Name.Length == 0) {
                RenderMembers(tree, ns);
                continue;
            }

            if (useFileScopedNamespace) {
                tree.Line($"namespace {ns.Name};");
                tree.NewLine();
                RenderMembers(tree, ns);
                continue;
            }

            tree.Text($"namespace {ns.Name} ");
            tree.StartCodeBlock();
            RenderMembers(tree, ns);
            tree.EndCodeBlock();
        }

        return tree.GetSourceText();
    }

    private static void RenderMembers(IRenderTreeBuilder tree, NamespaceBuilder ns) {
        for (var i = 0; i < ns.Members.Count; i++) {
            if (i > 0) {
                tree.NewLine();
            }

            ns.Members[i].RenderDeclaration(tree);
        }
    }

    /// <summary>A stable hint name for this file, e.g. <c>UserRepository.3f2a9c01b7e4d6a8.g.cs</c>.</summary>
    internal static string HintName(string name, string content) {
        return $"{CSharpIdentifier.Sanitize(name)}.{StableHash.Compute(content):x16}.g.cs";
    }
}

internal static class StableHash {
    /// <summary>64-bit FNV-1a hash, stable across processes and runtimes (unlike <see cref="string.GetHashCode()"/>).</summary>
    public static ulong Compute(string text) {
        const ulong offsetBasis = 14695981039346656037;
        const ulong prime = 1099511628211;

        var hash = offsetBasis;
        foreach (var c in text) {
            hash ^= c;
            hash *= prime;
        }

        return hash;
    }
}
